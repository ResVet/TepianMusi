// Compress the raw Blender exports (blender/out/*.glb) into public/models.
//
// Positions are left unquantized on purpose. Quantizing them moves each
// node's origin to its bounding box, which would break every pivot the site
// animates: clock hands, the book's spine, the lift span, wings, propellers.
// Normals and UVs are still quantized and everything is meshopt-compressed.
//
// Texture budget (decoded RGBA8 on the GPU is what hurts phones, not bytes on
// the wire): base colour 512 px, a few close-up surfaces 1024 px,
// roughness/metal 256 px, normals 512 px on station models and 256 px on
// background props.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions';
import { dedup, prune, weld, reorder, quantize, textureCompress } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import sharp from 'sharp';
import { readdirSync, statSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'blender', 'out');
const dst = join(root, 'public', 'models');
mkdirSync(dst, { recursive: true });

const props = new Set(['kelapa_a', 'kelapa_b', 'nipah', 'pohon', 'semak', 'kuntul', 'rumah_a', 'rumah_b',
  'rumah_c', 'rumah_d', 'rakit_a', 'rakit_b', 'jukung_hijau', 'jukung_biru']);
// Materials seen from arm's length during the close-up interactions.
const closeUp = /^(sepra|kayu_papan|songket|tikar_anyam)$/;

await MeshoptEncoder.ready;
await MeshoptDecoder.ready;
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });

const only = process.argv.slice(2);
let total = 0;
for (const f of readdirSync(src).filter((n) => n.endsWith('.glb'))) {
  const name = f.replace(/\.glb$/, '');
  if (only.length && !only.includes(name)) continue;
  const doc = await io.read(join(src, f));

  // Tag close-up textures by name so the resize pass can pick them out.
  const big = new Set();
  for (const m of doc.getRoot().listMaterials()) {
    if (!props.has(name) && closeUp.test(m.getName())) {
      const t = m.getBaseColorTexture();
      if (t) big.add(t);
    }
  }
  for (const t of doc.getRoot().listTextures()) t.setName(`${big.has(t) ? 'big_' : ''}${t.getName() || 'tex'}`);

  const nrm = props.has(name) ? 256 : 512;
  const webp = { encoder: sharp, targetFormat: 'webp', quality: 86, effort: 5 };
  await doc.transform(
    dedup({ keepUniqueNames: true }),
    prune({ keepLeaves: true }),
    weld(),
    reorder({ encoder: MeshoptEncoder, target: 'size' }),
    quantize({ pattern: /^(NORMAL|TEXCOORD_\d+|COLOR_\d+)$/, quantizeNormal: 10, quantizeTexcoord: 12 }),
    textureCompress({ ...webp, slots: /^baseColor/, pattern: /^big_/, resize: [1024, 1024] }),
    textureCompress({ ...webp, slots: /^baseColor/, pattern: /^(?!big_)/, resize: [props.has(name) ? 256 : 512, props.has(name) ? 256 : 512] }),
    textureCompress({ ...webp, slots: /^emissive/, resize: [512, 512] }),
    textureCompress({ ...webp, slots: /^metallicRoughness|^occlusion/, resize: [256, 256] }),
    textureCompress({ ...webp, quality: 90, slots: /^normal/, resize: [nrm, nrm] }),
  );
  doc.createExtension(EXTMeshoptCompression).setRequired(true)
    .setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });

  const out = join(dst, f);
  await io.write(out, doc);
  const kb = statSync(out).size / 1024;
  total += kb;
  console.log(`${name.padEnd(16)} ${(statSync(join(src, f)).size / 1048576).toFixed(2)} MB -> ${(kb / 1024).toFixed(2)} MB`);
}
console.log(`total ${(total / 1024).toFixed(2)} MB`);

// Byte sizes for an honest loading bar.
const sizes = {};
for (const f of readdirSync(dst).filter((n) => n.endsWith('.glb'))) sizes[f.replace(/\.glb$/, '')] = statSync(join(dst, f)).size;
mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'src/generated/models.ts'),
  '// Generated by scripts/optimize-models.mjs\n' +
  `export const MODEL_BYTES: Record<string, number> = ${JSON.stringify(sizes, null, 2)};\n`);
