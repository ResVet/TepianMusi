// Extract the few Solar icons the site uses into a tiny module so the client
// bundle never ships the full icon set. Solar icons: CC BY 4.0, 480 Design.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIconData, iconToSVG, iconToHTML, replaceIDs } from '@iconify/utils';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const set = JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json/solar/icons.json'), 'utf8'));

export const NAMES = [
  'map-linear', 'volume-loud-linear', 'volume-cross-linear', 'arrow-left-linear', 'close-linear',
  'download-minimalistic-linear', 'share-linear', 'restart-linear', 'check-circle-linear',
  'info-circle-linear', 'alt-arrow-right-linear', 'alt-arrow-down-linear', 'book-2-linear',
  'sun-2-linear', 'moon-linear', 'compass-linear', 'play-linear', 'hand-stars-linear',
  'cup-hot-linear', 'chef-hat-linear', 'lightbulb-bolt-linear', 'eye-linear', 'cursor-linear',
  'routing-2-linear', 'arrow-right-linear', 'ticket-linear', 'magnifer-linear',
];

const out = {};
for (const name of NAMES) {
  const data = getIconData(set, name);
  if (!data) throw new Error(`Solar icon not found: ${name}`);
  const svg = iconToSVG(data, { height: '1em' });
  out[name] = iconToHTML(replaceIDs(svg.body), { ...svg.attributes, 'aria-hidden': 'true', focusable: 'false', class: 'ic' });
}
mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'src/generated/icons.ts'),
  '// Generated by scripts/gen-icons.mjs from @iconify-json/solar (CC BY 4.0).\n' +
  `export const icons: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`);
console.log(`icons: ${Object.keys(out).length}`);
